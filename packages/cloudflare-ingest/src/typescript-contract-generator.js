import {
  normalizeContract,
} from "./contract-artifact.js";

export const TYPESCRIPT_CONTRACT_GENERATOR_VERSION = 1;

export function generateTypeScriptContractModule(
  artifact,
) {
  const normalized =
    normalizeArtifact(artifact);
  const contract =
    normalized.contract;
  const symbol =
    contractSymbol(
      contract.eventName,
      contract.version,
    );
  const attributesType =
    `${symbol}Attributes`;
  const validatorName =
    `validate${attributesType}`;
  const contractJson =
    JSON.stringify(
      contract,
      null,
      2,
    );

  const requiredLines =
    Object.entries(
      contract.required,
    ).map(
      ([attribute, constraint]) =>
        `  ${JSON.stringify(attribute)}: ${typescriptTypeForConstraint(
          constraint,
          attribute,
        )};`,
    );

  const forbiddenLines =
    contract.forbidden.map(
      (attribute) =>
        `  ${JSON.stringify(attribute)}?: never;`,
    );

  const typeLines = [
    ...requiredLines,
    ...forbiddenLines,
    "  [key: string]: unknown;",
  ];

  const checks = [
    ...Object.entries(
      contract.required,
    ).flatMap(
      ([attribute, constraint]) =>
        runtimeChecks(
          attribute,
          constraint,
        ),
    ),
    ...contract.forbidden.map(
      (attribute) =>
        `    !(Object.hasOwn(attributes, ${JSON.stringify(
          attribute,
        )}) && attributes[${JSON.stringify(
          attribute,
        )}] != null)`,
    ),
  ];

  const expression =
    checks.length === 0
      ? "true"
      : checks.join(" &&\n");

  return [
    "// Generated by ETLayer. Do not edit.",
    `// Generator version: ${TYPESCRIPT_CONTRACT_GENERATOR_VERSION}`,
    "",
    `export const eventName = ${JSON.stringify(
      contract.eventName,
    )} as const;`,
    `export const schemaVersion = ${contract.version} as const;`,
    "",
    "export const contract = " +
      contractJson +
      " as const;",
    "",
    `export type ${attributesType} = {`,
    ...typeLines,
    "};",
    "",
    `export function ${validatorName}(`,
    "  value: unknown,",
    `): value is ${attributesType} {`,
    "  if (!isRecord(value)) return false;",
    "",
    "  const attributes = value;",
    "",
    "  return (",
    expression,
    "  );",
    "}",
    "",
    "function isRecord(",
    "  value: unknown,",
    "): value is Record<string, unknown> {",
    "  return (",
    '    typeof value === "object" &&',
    "    value !== null &&",
    "    !Array.isArray(value)",
    "  );",
    "}",
    "",
  ].join("\n");
}

function normalizeArtifact(
  artifact,
) {
  if (
    !artifact ||
    typeof artifact !== "object" ||
    Array.isArray(artifact)
  ) {
    throw new TypeScriptContractGeneratorError(
      "artifact must be an object",
    );
  }

  if (
    artifact.apiVersion !== "v1" ||
    artifact.kind !== "Contract"
  ) {
    throw new TypeScriptContractGeneratorError(
      "artifact must be an ETLayer v1 Contract",
    );
  }

  return {
    ...artifact,
    contract:
      normalizeContract(
        artifact.contract,
      ),
  };
}

function contractSymbol(
  eventName,
  version,
) {
  const words =
    eventName
      .split(/[^A-Za-z0-9]+/)
      .filter(Boolean);

  const base =
    words
      .map(
        (word) =>
          word.charAt(0)
            .toUpperCase() +
          word.slice(1),
      )
      .join("") || "Event";

  return `${base}V${version}`;
}

function typescriptTypeForConstraint(
  constraint,
  attribute,
) {
  if (
    Object.hasOwn(
      constraint,
      "const",
    )
  ) {
    return (
      "typeof contract.required[" +
      JSON.stringify(attribute) +
      "][\"const\"]"
    );
  }

  switch (constraint.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "object":
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

function runtimeChecks(
  attribute,
  constraint,
) {
  const access =
    `attributes[${JSON.stringify(
      attribute,
    )}]`;
  const checks = [
    `    Object.hasOwn(attributes, ${JSON.stringify(
      attribute,
    )})`,
    `    ${access} != null`,
  ];

  if (constraint.type) {
    checks.push(
      runtimeTypeCheck(
        access,
        constraint.type,
      ),
    );
  }

  if (
    Object.hasOwn(
      constraint,
      "const",
    )
  ) {
    checks.push(
      `    ${access} === contract.required[${JSON.stringify(
        attribute,
      )}].const`,
    );
  }

  return checks;
}

function runtimeTypeCheck(
  access,
  type,
) {
  if (type === "integer") {
    return (
      `    typeof ${access} === "number" && Number.isSafeInteger(${access})`
    );
  }

  if (type === "object") {
    return (
      `    typeof ${access} === "object" && ${access} !== null && !Array.isArray(${access})`
    );
  }

  if (
    type === "string" ||
    type === "number" ||
    type === "boolean"
  ) {
    return (
      `    typeof ${access} === ${JSON.stringify(
        type,
      )}`
    );
  }

  return "    true";
}

export class TypeScriptContractGeneratorError extends Error {}
